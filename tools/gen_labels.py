lsig={a:H.signature(lbuf,a) for a in lnames if 0xC000<=a<=0xFFFF and not (lbuf[a-0xC000:a-0xC000+3]==lstub) and len(H.signature(lbuf,a))>=3}
def bestl(sig):
    ba,bs=None,0.0
    for a,s in lsig.items():
        r=difflib.SequenceMatcher(None,sig,s).ratio()
        if r>bs: bs,ba=r,a
    return ba,bs
